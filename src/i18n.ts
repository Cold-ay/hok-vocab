export const UI_MESSAGES: Record<UiLang, Record<MessageKey, string>> = {
  en, fr, es,
  'zh-TW': zhTW,
  'zh-CN': zhCN,
  ko, ja,
}

export type I18nKey = MessageKey

export interface I18nValue {
  t: (key: I18nKey) => string
  uiLang: UiLang
}

export const I18nContext = createContext<I18nValue>({
  t: (key) => en[key],
  uiLang: 'en',
})

export function mapFromLangToUiLang(fromLang: string): UiLang {
  if (fromLang === 'zh-TW') return 'zh-TW'
  if (fromLang === 'zh-CN') return 'zh-CN'
  const base = fromLang.split('-')[0]
  if (base === 'fr') return 'fr'
  if (base === 'es') return 'es'
  if (base === 'ko') return 'ko'
  if (base === 'ja') return 'ja'
  return 'en'
}

export function useI18n() {
  return useContext(I18nContext)
}

export function tpl(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))
}
